// LOOKUP FUNCTIONS
// =====================================================

const allUnits = [...chudUnits, ...chosenUnits, ...crusaderUnits, ...chadUnits];
const allBuildings = [...chudBuildings, ...chosenBuildings, ...crusaderBuildings, ...chadBuildings];

const unitMap = new Map<string, UnitDefinition>();
for (const u of allUnits) unitMap.set(u.id, u);

const buildingMap = new Map<string, BuildingDefinition>();
for (const b of allBuildings) buildingMap.set(b.id, b);

const upgradeMap = new Map<string, UpgradeDefinition>();
for (const u of upgrades) upgradeMap.set(u.id, u);

export function getUnitDefinition(id: string): UnitDefinition | undefined {
  return unitMap.get(id);
}

export function getBuildingDefinition(id: string): BuildingDefinition | undefined {
  return buildingMap.get(id);
}

export function getUpgradeDefinition(id: string): UpgradeDefinition | undefined {
  return upgradeMap.get(id);
}

export function getFactionUnits(faction: FactionId): UnitDefinition[] {
  return allUnits.filter(u => u.faction === faction);
}

export function getFactionBuildings(faction: FactionId): BuildingDefinition[] {
  return allBuildings.filter(b => b.faction === faction);
}

export function getFactionUpgrades(faction: FactionId): UpgradeDefinition[] {
  return upgrades.filter(u => u.faction === faction);
}

export function getAllFactionData(faction: FactionId) {
  return {
    units: getFactionUnits(faction),
    buildings: getFactionBuildings(faction),
    upgrades: getFactionUpgrades(faction),
  };
}

